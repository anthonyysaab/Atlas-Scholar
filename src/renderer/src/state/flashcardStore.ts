import { create } from "zustand";
import type { CardDraft, CardPassage, CardPatch, Deck, Flashcard, ReviewGrade } from "@shared/types";
import { withWikiConcepts } from "@renderer/study/wikiConcepts";
import { useLinksStore } from "./linksStore";
import { useSettingsStore } from "./settingsStore";

export const NO_CARDS: Flashcard[] = [];

const ACTIVE_DECK_KEY = "ra:flashcards:activeDeck";

function rememberDeck(id: string | null): void {
  try {
    if (id) localStorage.setItem(ACTIVE_DECK_KEY, id);
    else localStorage.removeItem(ACTIVE_DECK_KEY);
  } catch {
    // storage unavailable; the first deck is picked next time
  }
}

function recallDeck(): string | null {
  try {
    return localStorage.getItem(ACTIVE_DECK_KEY);
  } catch {
    return null;
  }
}

function message(error: unknown): string {
  return error instanceof Error ? error.message : String(error);
}

interface FlashcardState {
  decks: Deck[];
  decksLoaded: boolean;
  activeDeckId: string | null;
  cardsByDeck: Record<string, Flashcard[]>;
  /** Every deck's cards, loaded on demand to show which cards belong to a concept. */
  allCards: Flashcard[] | null;
  /** A card to reveal in the Cards tab, e.g. after clicking it under a concept. */
  focusCardId: string | null;
  /** Cards made from the selection or generated by the model, awaiting review before they are saved. */
  drafts: CardDraft[];
  generating: boolean;
  error: string | null;
  clearError: () => void;
  loadDecks: () => Promise<void>;
  selectDeck: (id: string) => Promise<void>;
  createDeck: (name: string) => Promise<Deck | null>;
  renameDeck: (id: string, name: string) => Promise<void>;
  removeDeck: (id: string) => Promise<void>;
  loadCards: (deckId: string) => Promise<void>;
  loadAllCards: () => Promise<void>;
  focusCard: (card: Pick<Flashcard, "id" | "deckId">) => Promise<void>;
  clearFocus: () => void;
  addDrafts: (drafts: CardDraft[]) => void;
  generate: (passages: CardPassage[], maxCards?: number) => Promise<boolean>;
  updateDraft: (index: number, patch: Partial<CardDraft>) => void;
  removeDraft: (index: number) => void;
  discardDrafts: () => void;
  saveDrafts: () => Promise<number>;
  addCard: (draft: CardDraft) => Promise<boolean>;
  updateCard: (id: string, patch: CardPatch) => Promise<void>;
  /** Add a concept to each card (keeping the ones it has); returns how many changed. */
  linkCards: (ids: readonly string[], conceptId: string) => Promise<number>;
  removeCard: (id: string) => Promise<void>;
  review: (id: string, grade: ReviewGrade) => Promise<Flashcard | null>;
  exportDeck: () => Promise<string | null>;
}

function replaceCard(cards: Flashcard[] | undefined, next: Flashcard): Flashcard[] {
  return (cards ?? []).map((card) => (card.id === next.id ? next : card));
}

function replaceInAll(all: Flashcard[] | null, next: Flashcard): Flashcard[] | null {
  return all ? replaceCard(all, next) : all;
}

export function incompleteDraft(draft: CardDraft): boolean {
  return !draft.question.trim() || !draft.answer.trim();
}

export const useFlashcardStore = create<FlashcardState>((set, get) => ({
  decks: [],
  decksLoaded: false,
  activeDeckId: null,
  cardsByDeck: {},
  allCards: null,
  focusCardId: null,
  drafts: [],
  generating: false,
  error: null,

  clearError: () => set({ error: null }),

  loadDecks: async () => {
    try {
      const decks = await window.api.flashcards.decks.list();
      const current = get().activeDeckId ?? recallDeck();
      const activeDeckId = decks.some((deck) => deck.id === current) ? current : (decks[0]?.id ?? null);
      set({ decks, decksLoaded: true, activeDeckId });
      if (activeDeckId) await get().loadCards(activeDeckId);
    } catch (error) {
      set({ decksLoaded: true, error: message(error) });
    }
  },

  selectDeck: async (id) => {
    if (!get().decks.some((deck) => deck.id === id)) return;
    set({ activeDeckId: id });
    rememberDeck(id);
    await get().loadCards(id);
  },

  createDeck: async (name) => {
    try {
      const deck = await window.api.flashcards.decks.create(name);
      set((state) => ({
        decks: [...state.decks, deck],
        activeDeckId: deck.id,
        cardsByDeck: { ...state.cardsByDeck, [deck.id]: [] },
        error: null
      }));
      rememberDeck(deck.id);
      return deck;
    } catch (error) {
      set({ error: message(error) });
      return null;
    }
  },

  renameDeck: async (id, name) => {
    try {
      const deck = await window.api.flashcards.decks.rename(id, name);
      set((state) => ({ decks: state.decks.map((entry) => (entry.id === id ? deck : entry)), error: null }));
    } catch (error) {
      set({ error: message(error) });
    }
  },

  removeDeck: async (id) => {
    try {
      await window.api.flashcards.decks.remove(id);
      const decks = get().decks.filter((deck) => deck.id !== id);
      const cardsByDeck = { ...get().cardsByDeck };
      delete cardsByDeck[id];
      const activeDeckId = get().activeDeckId === id ? (decks[0]?.id ?? null) : get().activeDeckId;
      set({ decks, cardsByDeck, activeDeckId, error: null });
      rememberDeck(activeDeckId);
      if (activeDeckId) await get().loadCards(activeDeckId);
    } catch (error) {
      set({ error: message(error) });
    }
  },

  loadCards: async (deckId) => {
    try {
      const cards = await window.api.flashcards.cards.list(deckId);
      set((state) => ({ cardsByDeck: { ...state.cardsByDeck, [deckId]: cards } }));
    } catch (error) {
      set({ error: message(error) });
    }
  },

  loadAllCards: async () => {
    try {
      set({ allCards: await window.api.flashcards.cards.all() });
    } catch (error) {
      set({ error: message(error) });
    }
  },

  focusCard: async (card) => {
    if (!get().decksLoaded) await get().loadDecks();
    if (get().activeDeckId !== card.deckId) await get().selectDeck(card.deckId);
    set({ focusCardId: card.id });
  },

  clearFocus: () => set({ focusCardId: null }),

  addDrafts: (drafts) => {
    if (drafts.length > 0) set((state) => ({ drafts: [...state.drafts, ...drafts], error: null }));
  },

  generate: async (passages, maxCards) => {
    if (passages.length === 0 || get().generating) return false;
    const settings = useSettingsStore.getState().settings;
    const providerId = settings?.activeProviderId ?? "";
    const model = settings?.activeChatModel ?? "";
    if (!providerId || !model) {
      set({ error: "Choose a model before generating cards." });
      return false;
    }
    set({ generating: true, error: null });
    try {
      const drafts = await window.api.flashcards.generate({
        providerId,
        model,
        passages,
        ...(maxCards !== undefined ? { maxCards } : {})
      });
      set((state) => ({ drafts: [...state.drafts, ...drafts] }));
      return true;
    } catch (error) {
      set({ error: message(error) });
      return false;
    } finally {
      set({ generating: false });
    }
  },

  updateDraft: (index, patch) =>
    set((state) => ({ drafts: state.drafts.map((draft, i) => (i === index ? { ...draft, ...patch } : draft)) })),

  removeDraft: (index) => set((state) => ({ drafts: state.drafts.filter((_, i) => i !== index) })),

  discardDrafts: () => set({ drafts: [] }),

  saveDrafts: async () => {
    const deckId = get().activeDeckId;
    const drafts = get().drafts;
    if (!deckId || drafts.length === 0) return 0;
    const unfinished = drafts.filter(incompleteDraft).length;
    if (unfinished > 0) {
      set({
        error: `${unfinished} card${unfinished === 1 ? " needs" : "s need"} both a question and an answer. Write the missing side or drop ${unfinished === 1 ? "it" : "them"}.`
      });
      return 0;
    }
    try {
      const graph = useLinksStore.getState().graph;
      const added = await window.api.flashcards.cards.add(
        deckId,
        drafts.map((draft) => withWikiConcepts(draft, graph))
      );
      set((state) => ({
        drafts: [],
        cardsByDeck: { ...state.cardsByDeck, [deckId]: [...(state.cardsByDeck[deckId] ?? []), ...added] },
        allCards: state.allCards ? [...state.allCards, ...added] : state.allCards,
        error: null
      }));
      return added.length;
    } catch (error) {
      set({ error: message(error) });
      return 0;
    }
  },

  addCard: async (draft) => {
    const deckId = get().activeDeckId;
    if (!deckId) return false;
    try {
      const added = await window.api.flashcards.cards.add(deckId, [withWikiConcepts(draft, useLinksStore.getState().graph)]);
      set((state) => ({
        cardsByDeck: { ...state.cardsByDeck, [deckId]: [...(state.cardsByDeck[deckId] ?? []), ...added] },
        allCards: state.allCards ? [...state.allCards, ...added] : state.allCards,
        error: null
      }));
      return added.length > 0;
    } catch (error) {
      set({ error: message(error) });
      return false;
    }
  },

  updateCard: async (id, patch) => {
    try {
      let next = patch;
      if (patch.question !== undefined || patch.answer !== undefined) {
        const current = Object.values(get().cardsByDeck)
          .flat()
          .find((card) => card.id === id);
        if (current && patch.conceptIds === undefined) {
          const merged = withWikiConcepts(
            { question: patch.question ?? current.question, answer: patch.answer ?? current.answer, conceptIds: current.conceptIds ?? [] },
            useLinksStore.getState().graph
          );
          if ((merged.conceptIds?.length ?? 0) !== (current.conceptIds?.length ?? 0)) next = { ...patch, conceptIds: merged.conceptIds ?? [] };
        }
      }
      const card = await window.api.flashcards.cards.update(id, next);
      set((state) => ({
        cardsByDeck: { ...state.cardsByDeck, [card.deckId]: replaceCard(state.cardsByDeck[card.deckId], card) },
        allCards: replaceInAll(state.allCards, card)
      }));
    } catch (error) {
      set({ error: message(error) });
    }
  },

  linkCards: async (ids, conceptId) => {
    if (!get().allCards) await get().loadAllCards();
    const byId = new Map((get().allCards ?? []).map((card) => [card.id, card]));
    let linked = 0;
    for (const id of ids) {
      const current = byId.get(id)?.conceptIds ?? [];
      if (current.includes(conceptId)) continue;
      await get().updateCard(id, { conceptIds: [...current, conceptId] });
      linked += 1;
    }
    return linked;
  },

  removeCard: async (id) => {
    try {
      await window.api.flashcards.cards.remove(id);
      set((state) => {
        const cardsByDeck: Record<string, Flashcard[]> = {};
        for (const [deckId, cards] of Object.entries(state.cardsByDeck)) {
          cardsByDeck[deckId] = cards.filter((card) => card.id !== id);
        }
        return { cardsByDeck, allCards: state.allCards?.filter((card) => card.id !== id) ?? null };
      });
    } catch (error) {
      set({ error: message(error) });
    }
  },

  review: async (id, grade) => {
    try {
      const card = await window.api.flashcards.cards.review(id, grade);
      set((state) => ({
        cardsByDeck: { ...state.cardsByDeck, [card.deckId]: replaceCard(state.cardsByDeck[card.deckId], card) },
        allCards: replaceInAll(state.allCards, card)
      }));
      return card;
    } catch (error) {
      set({ error: message(error) });
      return null;
    }
  },

  exportDeck: async () => {
    const deckId = get().activeDeckId;
    if (!deckId) return null;
    try {
      return await window.api.flashcards.exportAnki(deckId);
    } catch (error) {
      set({ error: message(error) });
      return null;
    }
  }
}));
